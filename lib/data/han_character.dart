import 'dart:convert';

class HanCharacter {
  final int? id;
  final String character;
  final String hanVietReading;
  final String meaning;
  /// Thành phần/bộ dùng để giải thích hoặc tra cứu chữ.
  final String radical;
  final String structure;
  final int difficulty;
  final int mastery;
  final List<String> examples;
  /// Mẹo liên tưởng; không nhất thiết là nguyên giải học thuật.
  final String? mnemonic;
  /// 'Hán' hoặc 'Nôm'.
  final String type;
  /// 1: xuất hiện trong lộ trình học; 0: chỉ xuất hiện trong từ điển.
  final bool inCurriculum;

  const HanCharacter({
    this.id,
    required this.character,
    required this.hanVietReading,
    required this.meaning,
    required this.radical,
    required this.structure,
    required this.difficulty,
    this.mastery = 0,
    this.examples = const [],
    this.mnemonic,
    this.type = 'Hán',
    this.inCurriculum = false,
  });

  bool get isNom => type == 'Nôm';
  bool get isHan => !isNom;

  HanCharacter copyWith({
    int? id,
    int? mastery,
    bool? inCurriculum,
    String? mnemonic,
  }) => HanCharacter(
    id: id ?? this.id,
    character: character,
    hanVietReading: hanVietReading,
    meaning: meaning,
    radical: radical,
    structure: structure,
    difficulty: difficulty,
    mastery: mastery ?? this.mastery,
    examples: examples,
    mnemonic: mnemonic ?? this.mnemonic,
    type: type,
    inCurriculum: inCurriculum ?? this.inCurriculum,
  );

  /// SQLite row mapper; folded fields are generated by the database service.
  Map<String, Object?> toDatabaseMap({bool? curriculumOverride}) => {
    'id': id,
    'character': character,
    'han_viet_reading': hanVietReading,
    'meaning': meaning,
    'radical': radical,
    'structure': structure,
    'difficulty': difficulty,
    'mastery': mastery,
    'examples_json': examples.isEmpty ? '[]' : _encodeExamples(examples),
    'mnemonic': mnemonic,
    'type': type,
    'in_curriculum': (curriculumOverride ?? inCurriculum) ? 1 : 0,
  };

  factory HanCharacter.fromDatabaseMap(Map<String, Object?> map) {
    final rawExamples = map['examples_json']?.toString();
    List<String> examples = const [];
    if (rawExamples != null && rawExamples.isNotEmpty) {
      try {
        final decoded = _decodeExamples(rawExamples);
        examples = decoded;
      } catch (_) {
        examples = const [];
      }
    }
    return HanCharacter(
      id: (map['id'] as num?)?.toInt(),
      character: map['character']?.toString() ?? '',
      hanVietReading: map['han_viet_reading']?.toString() ?? '',
      meaning: map['meaning']?.toString() ?? '',
      radical: map['radical']?.toString() ?? '',
      structure: map['structure']?.toString() ?? 'Chưa rõ',
      difficulty: (map['difficulty'] as num?)?.toInt() ?? 3,
      mastery: (map['mastery'] as num?)?.toInt() ?? 0,
      examples: examples,
      mnemonic: _nullableNonEmpty(map['mnemonic']?.toString()),
      type: _normalizeCharacterType(map['type']?.toString()),
      inCurriculum: (map['in_curriculum'] as num?)?.toInt() == 1,
    );
  }

  factory HanCharacter.fromDictionaryMap(Map<String, dynamic> map, {bool inCurriculum = false}) {
    final rawRadical = map['radical'] ?? map['radicals'];
    final radical = rawRadical is List
        ? (rawRadical.isEmpty ? '' : rawRadical.first.toString())
        : rawRadical?.toString() ?? '';
    final reading = map['han_viet_reading'] ?? map['sinoViet'] ?? map['hanViet'] ?? map['reading'];
    final meaning = map['meaning'] ?? map['meaningVi'] ?? map['meaning_vi'] ?? map['gloss'];
    final character = map['character'] ?? map['hanzi'] ?? map['char'];
    if (character == null || reading == null || meaning == null ||
        character.toString().trim().isEmpty || reading.toString().trim().isEmpty || meaning.toString().trim().isEmpty) {
      throw const FormatException('Mục từ cần có character, han_viet_reading và meaning.');
    }
    final rawExamples = map['examples'];
    final examples = rawExamples is List ? rawExamples.map((e) => e.toString()).toList() : const <String>[];
    return HanCharacter(
      character: character.toString().trim(),
      hanVietReading: reading.toString().trim(),
      meaning: meaning.toString().trim(),
      radical: radical,
      structure: map['structure']?.toString() ?? 'Chưa rõ',
      difficulty: (map['difficulty'] as num?)?.toInt() ?? (map['hskLevel'] as num?)?.toInt() ?? 3,
      mastery: (map['mastery'] as num?)?.toInt() ?? 0,
      examples: examples,
      mnemonic: _nullableNonEmpty(map['mnemonic']?.toString()),
      type: _normalizeCharacterType((map['type'] ?? map['character_type'])?.toString()),
      inCurriculum: inCurriculum || map['in_curriculum'] == true || map['in_curriculum'] == 1,
    );
  }
}

String _encodeExamples(List<String> examples) => jsonEncode(examples);

List<String> _decodeExamples(String value) =>
    (jsonDecode(value) as List<dynamic>).map((e) => e.toString()).toList();

class LessonUnit {
  final String title;
  final String subtitle;
  final List<String> characters;
  final String icon;
  final String type;

  const LessonUnit({
    required this.title,
    required this.subtitle,
    required this.characters,
    required this.icon,
    this.type = 'Hán',
  });

  bool get isNom => type == 'Nôm';
}


String _normalizeCharacterType(String? rawType) {
  final value = (rawType ?? '').trim().toLowerCase();
  if (value == 'nôm' || value == 'nom' || value == 'chữ nôm' || value == 'chu nom') {
    return 'Nôm';
  }
  return 'Hán';
}

String? _nullableNonEmpty(String? value) {
  final trimmed = value?.trim();
  return trimmed == null || trimmed.isEmpty ? null : trimmed;
}
